//! The Word looks PRD §5.2: which of asciidoctor-pdf 2.3's theme keys a Word export applies and
//! which it ignores, from `MAPPED_KEYS` (which `look.rs`'s own test holds to what `from_theme`
//! reads), and the documentation's table generated from it. Run with `UPDATE_WORD_THEME_KEYS=1`
//! to write `src/docs/modules/ROOT/partials/word-theme-keys.adoc` again.

use std::{
    collections::BTreeMap,
    path::{Path, PathBuf},
};

use adoc_docx::MAPPED_KEYS;

fn repository() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn reference_keys() -> Vec<String> {
    std::fs::read_to_string(repository().join("tests/fixtures/pdf/themes/reference-keys.txt"))
        .unwrap()
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_owned)
        .collect()
}

/// Whether `name` is an instance of the reference key `pattern`, whose `<…>` placeholders
/// stand for one or more name characters.
fn matches(pattern: &str, name: &str) -> bool {
    match pattern.find('<') {
        None => pattern == name,
        Some(open) => {
            let close = open + pattern[open..].find('>').unwrap();
            let (literal, rest) = (&pattern[..open], &pattern[close + 1..]);
            let Some(name) = name.strip_prefix(literal) else {
                return false;
            };
            (1..=name.len()).any(|taken| {
                name[..taken]
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
                    && matches(rest, &name[taken..])
            })
        }
    }
}

/// Whether a Word export applies the reference key `key`: a mapped key is it, or is one of
/// the names it stands for (`header_<side>_<position>_content` for `header_recto_left_content`).
fn applied(key: &str) -> bool {
    MAPPED_KEYS
        .iter()
        .any(|mapped| *mapped == key || matches(key, &mapped.replace("<n>", "1")))
}

/// The category a key is listed under: its first word, or the two of a compound one.
fn category(key: &str) -> String {
    const COMPOUND: &[&str] = &[
        "callout_list",
        "description_list",
        "footnotes",
        "index",
        "kbd",
        "list",
        "mark",
        "menu",
        "olist",
        "page",
        "prose",
        "quote",
        "section",
        "table",
        "thematic_break",
        "title_page",
        "toc",
        "ulist",
        "verse",
    ];
    COMPOUND
        .iter()
        .filter(|prefix| key.starts_with(*prefix))
        .max_by_key(|prefix| prefix.len())
        .map_or_else(
            || key.split('_').next().unwrap_or(key).to_owned(),
            |prefix| (*prefix).to_owned(),
        )
}

fn partial() -> String {
    let keys = reference_keys();
    let applied_count = keys.iter().filter(|key| applied(key)).count();
    let mut out = String::from(
        "// Generated by `cargo test -p adoc-docx --test theme_keys` from adoc-docx's MAPPED_KEYS.\n\
         // Run it with UPDATE_WORD_THEME_KEYS=1 to regenerate; do not edit by hand.\n\n",
    );
    out.push_str(&format!(
        "Of the {} keys in asciidoctor-pdf 2.3's Theme Keys Reference, a Word export applies {} \
         and ignores {}.\n",
        keys.len(),
        applied_count,
        keys.len() - applied_count,
    ));
    let mut categories: BTreeMap<String, Vec<&String>> = BTreeMap::new();
    for key in &keys {
        categories.entry(category(key)).or_default().push(key);
    }
    for (category, keys) in categories {
        out.push_str(&format!(
            "\n[#word-key-{}]\n=== {category}\n\n[cols=\"3,1\"]\n|===\n|Key |In Word\n",
            category.replace('_', "-")
        ));
        for key in keys {
            out.push_str(&format!(
                "\n|`{key}`\n|{}\n",
                if applied(key) { "applied" } else { "ignored" }
            ));
        }
        out.push_str("|===\n");
    }
    let extra: Vec<&str> = MAPPED_KEYS
        .iter()
        .copied()
        .filter(|mapped| {
            !keys
                .iter()
                .any(|key| key == mapped || matches(key, &mapped.replace("<n>", "1")))
        })
        .collect();
    if !extra.is_empty() {
        out.push_str(
            "\n[#word-key-extra]\n=== Keys beyond the reference\n\n\
             A Word export also applies these keys, which the reference does not list.\n\n",
        );
        for key in extra {
            out.push_str(&format!("* `{key}`\n"));
        }
    }
    out
}

#[test]
fn the_word_theme_keys_table_is_current() {
    let file = repository().join("src/docs/modules/ROOT/partials/word-theme-keys.adoc");
    let generated = partial();
    if std::env::var_os("UPDATE_WORD_THEME_KEYS").is_some() {
        std::fs::write(&file, &generated).unwrap();
    }
    let written = std::fs::read_to_string(&file).unwrap_or_default();
    assert!(
        written == generated,
        "{} is out of date: run `UPDATE_WORD_THEME_KEYS=1 cargo test -p adoc-docx --test theme_keys`",
        file.display()
    );
}

#[test]
fn every_mapped_key_is_a_theme_key() {
    // A mapped key the reference does not list is a typo, unless it is known here:
    // `heading_font_size` is read by the reader every heading's font shares, before the
    // levels' own sizes.
    const BEYOND_REFERENCE: &[&str] = &["heading_font_size"];
    let keys = reference_keys();
    for mapped in MAPPED_KEYS {
        assert!(
            BEYOND_REFERENCE.contains(mapped)
                || keys
                    .iter()
                    .any(|key| key == mapped || matches(key, &mapped.replace("<n>", "1"))),
            "{mapped} is not in asciidoctor-pdf's Theme Keys Reference"
        );
    }
}
