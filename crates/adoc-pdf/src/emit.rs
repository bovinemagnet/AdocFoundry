/// The lines a block can take at most, estimated generously from its text: each line of code
/// or verse, a line for every 60 characters of a paragraph, and one for the spacing around each
/// block. `None` when its height cannot be told from its text: images, diagrams, media, tables,
/// maths, raw and unsupported content.
fn estimated_lines(block: &ViewBlock) -> Option<usize> {
    const CHARACTERS_PER_LINE: usize = 60;
    fn text_lines(text: &str) -> usize {
        text.lines()
            .map(|line| 1 + line.chars().count() / CHARACTERS_PER_LINE)
            .sum::<usize>()
            .max(1)
    }
    fn inline_lines(inlines: &[ViewInline]) -> usize {
        1 + ViewInline::plain_text(inlines).chars().count() / CHARACTERS_PER_LINE
    }
    fn blocks_lines(blocks: &[ViewBlock]) -> Option<usize> {
        blocks
            .iter()
            .map(|block| estimated_lines(block).map(|lines| lines + 1))
            .sum()
    }
    match &block.kind {
        ViewKind::Paragraph(content) => Some(inline_lines(content)),
        ViewKind::Heading { title, .. } => Some(inline_lines(title) + 1),
        ViewKind::Section { title, blocks, .. } => {
            Some(inline_lines(title) + 1 + blocks_lines(blocks)?)
        }
        ViewKind::List { items, .. } => items
            .iter()
            .map(|item| Some(inline_lines(&item.content) + blocks_lines(&item.blocks)?))
            .sum(),
        ViewKind::DescriptionList(items) => items
            .iter()
            .map(|item| {
                Some(
                    inline_lines(&item.term)
                        + inline_lines(&item.content)
                        + blocks_lines(&item.blocks)?,
                )
            })
            .sum(),
        ViewKind::CalloutList(items) => items
            .iter()
            .map(|item| Some(inline_lines(&item.content) + blocks_lines(&item.blocks)?))
            .sum(),
        ViewKind::Admonition { blocks, .. }
        | ViewKind::Quote { blocks, .. }
        | ViewKind::Sidebar(blocks)
        | ViewKind::Example(blocks)
        | ViewKind::Open(blocks) => Some(blocks_lines(blocks)? + 2),
        ViewKind::Code { text, .. } | ViewKind::Literal(text) | ViewKind::Verse { text, .. } => {
            Some(text_lines(text) + 1)
        }
        ViewKind::ThematicBreak => Some(1),
        _ => None,
    }
}

/// Listing text with each callout's circled number at the end of its line.
fn with_callouts(text: &str, callouts: &[adoc_render::Callout]) -> String {
    if callouts.is_empty() {
        return text.to_owned();
    }
    let mut out = String::new();
    for (index, line) in text.split('\n').enumerate() {
        if index > 0 {
            out.push('\n');
        }
        out.push_str(line.trim_end());
        for callout in callouts.iter().filter(|callout| callout.line == index) {
            out.push(' ');
            out.push(circled(callout.number));
        }
    }
    out
}

/// The lines of a highlighted listing as Typst: for each line of `text`, its runs as
/// `(text, fill, bold, italic)`, with the line's callouts after it as `with_callouts` writes
/// them. Tabs are expanded to `raw`'s two-column stops, as `raw` shows them. Only the run text
/// is the document's, and it is always a string literal.
fn highlighted_lines(
    text: &str,
    runs: &[(Range<usize>, Style)],
    callouts: &[adoc_render::Callout],
) -> String {
    let mut lines = Vec::new();
    let mut start = 0;
    for (index, line) in text.split('\n').enumerate() {
        let has_callouts = callouts.iter().any(|callout| callout.line == index);
        let end = start
            + if has_callouts {
                line.trim_end().len()
            } else {
                line.len()
            };
        let mut column = 0;
        let mut parts = Vec::new();
        for (range, style) in runs {
            let (from, to) = (range.start.max(start), range.end.min(end));
            if from >= to {
                continue;
            }
            let mut piece = String::new();
            for c in text[from..to].chars() {
                if c == '\t' {
                    let spaces = 2 - column % 2;
                    piece.extend(std::iter::repeat_n(' ', spaces));
                    column += spaces;
                } else {
                    piece.push(c);
                    column += 1;
                }
            }
            parts.push(run(&piece, style));
        }
        for callout in callouts.iter().filter(|callout| callout.line == index) {
            parts.push(run(
                &format!(" {}", circled(callout.number)),
                &Style::default(),
            ));
        }
        lines.push(format!(
            "({}{})",
            parts.join(", "),
            if parts.len() == 1 { "," } else { "" }
        ));
        start += line.len() + 1;
    }
    let trailing = if lines.len() == 1 { "," } else { "" };
    format!("{}{trailing}", lines.join(", "))
}

/// A highlighted run as Typst: its text, then its colour, weight and slant.
fn run(text: &str, style: &Style) -> String {
    let fill = match style.color {
        Some([red, green, blue]) => format!("rgb({red}, {green}, {blue})"),
        None => "none".to_owned(),
    };
    format!(
        "({}, {fill}, {}, {})",
        string(text),
        style.bold,
        style.italic
    )
}

/// The circled digit for a callout number, as asciidoctor-pdf's `circled` glyphs.
fn circled(number: usize) -> char {
    match number {
        1..=20 => char::from_u32(0x2460 + number as u32 - 1).unwrap_or('?'),
        _ => '?',
    }
}

/// An image size attribute as a Typst length: a percentage, or pixels at 96 dpi.
fn image_size(value: &str) -> Option<String> {
    image_extent(value).map(|extent| match extent {
        Natural::Percent(percent) => {
            format!("{}%", typst::number(percent).trim_end_matches(".0"))
        }
        Natural::Points(points) => typst::points(points),
        Natural::Typst => "auto".to_owned(),
    })
}

/// An image size attribute: a percentage, or a length, pixels at 96 dpi when it has no unit.
fn image_extent(value: &str) -> Option<Natural> {
    let value = value.trim();
    if let Some(percent) = value.strip_suffix('%') {
        return percent.trim().parse().ok().map(Natural::Percent);
    }
    let (number, unit) = match value.find(|c: char| !(c.is_ascii_digit() || c == '.')) {
        Some(split) => value.split_at(split),
        None => (value, "px"),
    };
    let number: f64 = number.parse().ok()?;
    crate::theme::to_pt(number, unit.trim()).map(Natural::Points)
}

/// A hash of `path` that is the same in every process, for stable virtual paths.
fn stable_hash(path: &Path) -> String {
    // FNV-1a over the path's bytes.
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in path.to_string_lossy().as_bytes() {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    format!("{hash:016x}")
}

