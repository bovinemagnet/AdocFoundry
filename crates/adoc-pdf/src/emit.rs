//! The view tree written as the body of a Typst document. Every block and inline becomes a call
//! to one of the template's `adoc-` functions or a Typst element, with all document text in
//! string literals, so the theme decides how it looks and the document can never inject Typst.

use std::{
    collections::{HashMap, HashSet},
    fmt::Write as _,
    ops::Range,
    path::{Path, PathBuf},
};

use adoc_core::FileAccess;

use adoc_render::{
    AdmonitionKind, Align, CellStyle, ColumnWidth, DiagramView, ListKind, MediaKind, SourceSpan,
    VAlign, ViewBlock, ViewCell, ViewImage, ViewInline, ViewKind, ViewTable, ViewTree,
};

use crate::highlight::{Highlighter, Style};
use crate::typst::{self, string, text};

/// One page of the document: a whole article, or a page of a book.
#[derive(Clone, Debug)]
pub struct PageView {
    /// A short key unique in the document, used to namespace the page's labels.
    pub key: String,
    pub view: ViewTree,
    /// How far the page's sections move down: 0 for an article, the page's nav depth in a book.
    pub depth: u8,
}

/// The generated body, the files it uses and where each part came from.
#[derive(Clone, Debug, Default)]
pub struct Emitted {
    pub source: String,
    /// Virtual path, real file.
    pub files: Vec<(String, PathBuf)>,
    pub map: SourceMap,
    /// Images that could not be shown, missing or unreadable, and where they were written.
    pub missing: Vec<(String, SourceSpan)>,
    /// Formulas that could not be typeset, why, and where they were written.
    pub unconverted: Vec<(String, SourceSpan)>,
}

/// Generated byte ranges and the AsciiDoc spans they were emitted for, outermost first.
#[derive(Clone, Debug, Default)]
pub struct SourceMap {
    entries: Vec<(Range<usize>, SourceSpan)>,
}

impl SourceMap {
    /// The innermost span emitted around `offset` in the generated source.
    #[must_use]
    pub fn lookup(&self, offset: usize) -> Option<&SourceSpan> {
        self.entries
            .iter()
            .filter(|(range, _)| range.start <= offset && offset < range.end)
            .min_by_key(|(range, _)| range.end - range.start)
            .map(|(_, span)| span)
    }

    pub(crate) fn shift(&mut self, by: usize) {
        for (range, _) in &mut self.entries {
            range.start += by;
            range.end += by;
        }
    }
}

/// What the emitter needs to know beyond the pages.
#[derive(Clone, Debug, Default)]
pub struct EmitOptions {
    /// Highlight source blocks by language.
    pub highlight: bool,
    /// The site cross references out of the document link to, for a book.
    pub site_url: Option<String>,
    /// `toclevels`: sections deeper than this are left out of the outline.
    pub toc_levels: u8,
    /// Addresses of pages outside the document, for references to them.
    pub page_urls: HashMap<PathBuf, String>,
    /// Which image files may be read.
    pub access: FileAccess,
}

pub(crate) struct Emitter<'a> {
    options: &'a EmitOptions,
    out: String,
    files: Vec<(String, PathBuf)>,
    file_paths: HashMap<PathBuf, String>,
    map: SourceMap,
    missing: Vec<(String, SourceSpan)>,
    unconverted: Vec<(String, SourceSpan)>,
    /// The block being written, for what is reported about its inlines.
    span: SourceSpan,
    /// Every label the document defines, so a reference to anything else is left as text.
    labels: HashSet<String>,
    /// Page file to page key, for references between the pages of a book.
    pages: HashMap<PathBuf, String>,
    key: String,
    depth: u8,
    source: PathBuf,
    ulist_depth: usize,
    olist_depth: usize,
    highlighter: Highlighter,
}

/// What follows each block of a run.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Gaps {
    /// The page's flow: every block's bottom margin, the last one's too.
    Flow,
    /// Inside a container: no margin after the last block.
    Inside,
    /// Inside a list item: the item spacing between blocks.
    Items,
}

/// The label of `id` on page `key`; the page's own label when `id` is empty.
pub(crate) fn label_name(key: &str, id: &str) -> String {
    if id.is_empty() {
        key.to_owned()
    } else {
        format!("{key}#{id}")
    }
}

impl<'a> Emitter<'a> {
    pub(crate) fn new(pages: &[PageView], options: &'a EmitOptions) -> Self {
        let mut labels = HashSet::new();
        for page in pages {
            labels.insert(label_name(&page.key, ""));
            collect_labels(&page.key, &page.view.blocks, &mut labels);
            for note in &page.view.footnotes {
                labels.insert(label_name(&page.key, &footnote_id(note.number)));
            }
        }
        Self {
            options,
            out: String::new(),
            files: Vec::new(),
            file_paths: HashMap::new(),
            map: SourceMap::default(),
            missing: Vec::new(),
            unconverted: Vec::new(),
            span: SourceSpan::default(),
            labels,
            pages: pages
                .iter()
                .map(|page| (page.view.source.clone(), page.key.clone()))
                .collect(),
            key: String::new(),
            depth: 0,
            source: PathBuf::new(),
            ulist_depth: 0,
            olist_depth: 0,
            highlighter: Highlighter::new(),
        }
    }

    pub(crate) fn finish(self) -> Emitted {
        Emitted {
            source: self.out,
            files: self.files,
            map: self.map,
            missing: self.missing,
            unconverted: self.unconverted,
        }
    }

    /// A formula as typeset maths, or `None` when it cannot be converted: it is then shown as its
    /// source, and why is reported against the block it is in.
    fn stem(&mut self, latex: bool, source: &str, block: bool) -> Option<String> {
        let notation = if latex {
            adoc_math::Notation::Latex
        } else {
            adoc_math::Notation::AsciiMath
        };
        match adoc_math::to_typst(notation, source) {
            Ok(math) => Some(format!(
                "#adoc-stem({}, {}, block: {block})",
                string(math.as_str()),
                string(source.trim())
            )),
            Err(error) => {
                self.unconverted.push((error.message, self.span.clone()));
                None
            }
        }
    }

    pub(crate) fn push(&mut self, text: &str) {
        self.out.push_str(text);
    }

    /// Starts writing `page`: its labels and references are resolved against its key.
    pub(crate) fn begin_page(&mut self, page: &PageView) {
        self.key = page.key.clone();
        self.depth = page.depth;
        self.source = page.view.source.clone();
    }

    /// A label value for `id` on the current page.
    pub(crate) fn label(&self, id: &str) -> String {
        format!("label({})", string(&label_name(&self.key, id)))
    }

    /// An anchor other content can link to.
    pub(crate) fn anchor(&mut self, id: &str) {
        let label = self.label(id);
        let _ = write!(self.out, "#metadata(none)#{label}");
    }

    /// The page's blocks, with the first paragraph of an article's preamble as the lead.
    pub(crate) fn page_body(&mut self, view: &ViewTree) {
        let lead = view.title.is_some()
            && view
                .blocks
                .iter()
                .any(|block| matches!(block.kind, ViewKind::Section { .. }))
            && view.blocks.first().is_some_and(|block| {
                matches!(block.kind, ViewKind::Paragraph(_)) && block.roles.is_empty()
            });
        if lead {
            let mut blocks = view.blocks.clone();
            blocks[0].roles.push("lead".to_owned());
            self.blocks(&blocks, Gaps::Flow);
        } else {
            self.blocks(&view.blocks, Gaps::Flow);
        }
    }

    /// The page's footnotes, gathered where asciidoctor-pdf puts them.
    pub(crate) fn footnotes(&mut self, view: &ViewTree) {
        if view.footnotes.is_empty() {
            return;
        }
        self.push("#adoc-footnotes((");
        for note in &view.footnotes {
            let label = self.label(&footnote_id(note.number));
            let content = self.inlines(&note.content);
            let _ = write!(
                self.out,
                "({}, {label}, [#metadata(none)#{label}{content}]), ",
                note.number
            );
        }
        self.push("))\n\n");
    }

    /// `blocks` with each one's bottom margin after it, as Prawn spaces blocks.
    pub(crate) fn blocks(&mut self, blocks: &[ViewBlock], gaps: Gaps) {
        for (index, block) in blocks.iter().enumerate() {
            self.block(block);
            let last = index + 1 == blocks.len();
            if last && gaps != Gaps::Flow {
                continue;
            }
            let gap = match (&block.kind, gaps) {
                (ViewKind::Section { .. } | ViewKind::Heading { .. } | ViewKind::PageBreak, _) => {
                    continue;
                }
                (_, Gaps::Items) => "list-gap",
                (ViewKind::Paragraph(_), _) => "prose-bottom",
                _ => "block-bottom",
            };
            let _ = writeln!(self.out, "#v({gap})\n");
        }
    }

    /// Blocks inside a container: no margin after the last.
    fn content(&mut self, blocks: &[ViewBlock]) -> String {
        let start = self.out.len();
        self.blocks(blocks, Gaps::Inside);
        let body = self.out.split_off(start);
        format!("[{body}]")
    }

    /// An item's text, then its blocks, the item spacing apart.
    fn item_body(&mut self, content: &[ViewInline], blocks: &[ViewBlock], gaps: Gaps) -> String {
        // The trailing break makes the text a paragraph, spaced as Prawn spaces lines.
        let mut body = self.inlines(content);
        if blocks.is_empty() && !body.is_empty() {
            body.push_str("\n\n");
        }
        if !blocks.is_empty() {
            let gap = if gaps == Gaps::Items {
                "list-gap"
            } else {
                "prose-bottom"
            };
            if !body.is_empty() {
                let _ = write!(body, "\n\n#v({gap})\n\n");
            }
            let start = self.out.len();
            self.blocks(blocks, gaps);
            body.push_str(&self.out.split_off(start));
        }
        body
    }

    fn record<F: FnOnce(&mut Self)>(&mut self, span: &SourceSpan, emit: F) {
        let start = self.out.len();
        emit(self);
        let end = self.out.len();
        if end > start {
            self.map.entries.push((start..end, span.clone()));
        }
    }

    fn block(&mut self, block: &ViewBlock) {
        let span = block.span.clone();
        self.span = span.clone();
        self.record(&span, |this| {
            // A titled block and its caption are one element, so the gap between them is the
            // theme's caption margin rather than a block's.
            let owns_title = matches!(
                block.kind,
                ViewKind::Section { .. }
                    | ViewKind::Heading { .. }
                    | ViewKind::Sidebar(_)
                    | ViewKind::Admonition { .. }
            );
            match this.caption_text(block).filter(|_| !owns_title) {
                Some(caption) => {
                    let below = matches!(block.kind, ViewKind::Image(_) | ViewKind::Diagram(_));
                    let start = this.out.len();
                    this.block_inner(block);
                    let body = this.out.split_off(start);
                    let _ = writeln!(
                        this.out,
                        "#adoc-captioned({}[{caption}], [{}], below: {below})\n",
                        fits_argument(block),
                        body.trim_end()
                    );
                }
                None => this.block_inner(block),
            }
        });
    }

    fn caption_text(&mut self, block: &ViewBlock) -> Option<String> {
        if matches!(block.kind, ViewKind::Example(_)) && block.options.contains("collapsible") {
            let title = if block.title.is_empty() {
                text("Details")
            } else {
                self.inlines(&block.title)
            };
            return Some(format!("{}{title}", text("\u{25bc} ")));
        }
        if block.title.is_empty() {
            return None;
        }
        let mut out = String::new();
        if let Some(caption) = &block.caption {
            out.push_str(&text(&format!("{caption} ")));
        }
        out.push_str(&self.inlines(&block.title));
        Some(out)
    }

    fn block_inner(&mut self, block: &ViewBlock) {
        if let (Some(id), false) = (&block.id, matches!(block.kind, ViewKind::Section { .. })) {
            let id = id.clone();
            self.anchor(&id);
        }
        match &block.kind {
            ViewKind::Section {
                level,
                number,
                title,
                blocks,
            } => {
                let section_level = *level;
                let level = section_level + self.depth;
                let mut heading = String::new();
                if let Some(number) = number {
                    heading.push_str(&text(&format!("{number} ")));
                }
                heading.push_str(&self.inlines(title));
                let outlined = section_level + self.depth <= self.options.toc_levels;
                let label = block
                    .id
                    .as_deref()
                    .map(|id| format!("#{}", self.label(id)))
                    .unwrap_or_default();
                let _ = writeln!(
                    self.out,
                    "#heading(level: {}, outlined: {outlined}, bookmarked: true)[{heading}]{label}\n",
                    u32::from(level) + 1
                );
                if block.style.as_deref() == Some("index") {
                    // An `[index]` section is the index, generated from the document's terms.
                    self.push("#adoc-index()\n\n");
                } else {
                    self.blocks(blocks, Gaps::Flow);
                }
            }
            ViewKind::Heading { level, title } => {
                let heading = self.inlines(title);
                let _ = writeln!(
                    self.out,
                    "#heading(level: {}, outlined: false, bookmarked: false)[{heading}]\n",
                    u32::from(level + self.depth) + 1
                );
            }
            ViewKind::Paragraph(content) => {
                let body = self.inlines(content);
                if block.roles.is_empty() {
                    let _ = writeln!(self.out, "{body}\n");
                } else {
                    let roles: Vec<String> = block.roles.iter().map(|role| string(role)).collect();
                    let _ = writeln!(
                        self.out,
                        "#adoc-paragraph(({},), [{body}])\n",
                        roles.join(", ")
                    );
                }
            }
            ViewKind::List { kind, items } => {
                let (markers, depth): (Vec<String>, _) = match kind {
                    ListKind::Ordered => {
                        self.olist_depth += 1;
                        let depth = self.olist_depth;
                        let style = block.style.as_deref().unwrap_or("arabic");
                        let markers = ordered_numbers(block, items.len())
                            .into_iter()
                            .map(|number| typst::text(&ordered_marker(style, number)))
                            .collect();
                        (markers, depth)
                    }
                    ListKind::Unordered | ListKind::Checklist => {
                        self.ulist_depth += 1;
                        let depth = self.ulist_depth;
                        let markers = items
                            .iter()
                            .map(|item| {
                                let marker = match item.checked {
                                    Some(true) => "\u{2611}",
                                    Some(false) => "\u{2610}",
                                    None => unordered_marker(depth),
                                };
                                typst::text(marker)
                            })
                            .collect();
                        (markers, depth)
                    }
                };
                let _ = depth;
                let mut bodies = Vec::new();
                for item in items {
                    let body = self.item_body(&item.content, &item.blocks, Gaps::Items);
                    bodies.push(format!("[{body}]"));
                }
                match kind {
                    ListKind::Ordered => self.olist_depth -= 1,
                    _ => self.ulist_depth -= 1,
                }
                let markers: Vec<String> =
                    markers.iter().map(|marker| format!("[{marker}]")).collect();
                let _ = writeln!(
                    self.out,
                    "#adoc-list(({},), ({},))\n",
                    markers.join(", "),
                    bodies.join(", ")
                );
            }
            ViewKind::DescriptionList(items) => {
                let style = block.style.as_deref();
                let mut entries = Vec::new();
                for item in items {
                    let term = self.inlines(&item.term);
                    let description = self.item_body(&item.content, &item.blocks, Gaps::Inside);
                    let description = if description.trim().is_empty() {
                        "none".to_owned()
                    } else {
                        format!("[{description}]")
                    };
                    entries.push((term, description));
                }
                match style {
                    Some("qanda") => {
                        let markers: Vec<String> = (1..=entries.len())
                            .map(|number| format!("[{}]", text(&format!("{number}."))))
                            .collect();
                        let bodies: Vec<String> = entries
                            .iter()
                            .map(|(term, description)| {
                                let description = if description == "none" {
                                    String::new()
                                } else {
                                    format!("\n\n#v(list-gap)\n\n#{description}")
                                };
                                format!("[#emph[{term}]{description}]")
                            })
                            .collect();
                        let _ = writeln!(
                            self.out,
                            "#adoc-list(({},), ({},))\n",
                            markers.join(", "),
                            bodies.join(", ")
                        );
                    }
                    Some("horizontal") => {
                        let entries: Vec<String> = entries
                            .iter()
                            .map(|(term, description)| format!("([{term}], {description})"))
                            .collect();
                        let _ = writeln!(self.out, "#adoc-hlist(({},))\n", entries.join(", "));
                    }
                    _ => {
                        let entries: Vec<String> = entries
                            .iter()
                            .map(|(term, description)| format!("([{term}], {description})"))
                            .collect();
                        let _ = writeln!(self.out, "#adoc-dlist(({},))\n", entries.join(", "));
                    }
                }
            }
            ViewKind::CalloutList(items) => {
                let mut entries = Vec::new();
                for item in items {
                    let body = self.item_body(&item.content, &item.blocks, Gaps::Items);
                    entries.push(format!("({}, [{body}])", item.number));
                }
                let _ = writeln!(self.out, "#adoc-callouts(({},))\n", entries.join(", "));
            }
            ViewKind::Admonition { kind, blocks } => {
                let body = self.content(blocks);
                let title = self.caption_text(block);
                let body = match title {
                    Some(title) => format!(
                        "[#block(sticky: true, strong[{title}])\n\n#v(prose-bottom)\n\n#{body}]"
                    ),
                    None => body,
                };
                let _ = writeln!(
                    self.out,
                    "#adoc-admonition({}{}, {}, {body})\n",
                    fits_argument(block),
                    string(admonition_name(*kind)),
                    string(admonition_label(*kind))
                );
            }
            ViewKind::Code {
                language,
                text,
                callouts,
            } => {
                let code = with_callouts(text, callouts);
                let highlighted = match language {
                    Some(language) if self.options.highlight => self
                        .highlighter
                        .highlight(language, text)
                        .map(|runs| highlighted_lines(text, &runs, callouts)),
                    _ => None,
                };
                let lang = match language {
                    Some(language) if self.options.highlight && highlighted.is_none() => {
                        format!(", lang: {}", string(language))
                    }
                    _ => String::new(),
                };
                let raw = format!("raw({}, block: true{lang})", string(&code));
                let body = match highlighted {
                    Some(lines) => format!("adoc-highlighted(({lines}), {raw})"),
                    None => raw,
                };
                let _ = writeln!(self.out, "#adoc-code({}{body})\n", fits_argument(block));
            }
            ViewKind::Literal(text) => {
                let _ = writeln!(
                    self.out,
                    "#adoc-code({}raw({}, block: true))\n",
                    fits_argument(block),
                    string(text)
                );
            }
            ViewKind::Quote {
                attribution,
                citation,
                blocks,
            } => {
                let body = self.content(blocks);
                let _ = writeln!(
                    self.out,
                    "#adoc-quote({}{body}, {}, {})\n",
                    fits_argument(block),
                    optional_string(attribution.as_deref()),
                    optional_string(citation.as_deref())
                );
            }
            ViewKind::Verse {
                attribution,
                citation,
                text,
            } => {
                let lines: Vec<String> = text.split('\n').map(verbatim_line).collect();
                let _ = writeln!(
                    self.out,
                    "#adoc-quote({}[{}], {}, {}, prefix: \"verse\")\n",
                    fits_argument(block),
                    lines.join("#linebreak()"),
                    optional_string(attribution.as_deref()),
                    optional_string(citation.as_deref())
                );
            }
            ViewKind::Sidebar(blocks) => {
                let title = self
                    .caption_text(block)
                    .map_or_else(|| "none".to_owned(), |title| format!("[{title}]"));
                let body = self.content(blocks);
                let fits = fits_argument(block);
                let _ = writeln!(
                    self.out,
                    "#adoc-container({fits}\"sidebar\", {title}, {body})\n"
                );
            }
            ViewKind::Example(blocks) if block.options.contains("collapsible") => {
                // As asciidoctor-pdf draws one: its caption, then its blocks, indented.
                let body = self.content(blocks);
                let _ = writeln!(self.out, "#adoc-collapsible({body})\n");
            }
            ViewKind::Example(blocks) => {
                let body = self.content(blocks);
                let fits = fits_argument(block);
                let _ = writeln!(
                    self.out,
                    "#adoc-container({fits}\"example\", none, {body})\n"
                );
            }
            ViewKind::Open(blocks) => {
                let body = self.content(blocks);
                let _ = writeln!(self.out, "#adoc-open({body})\n");
            }
            ViewKind::Table(table) => {
                self.table(block, table);
            }
            ViewKind::Image(image) => {
                self.block_image(block, image);
            }
            ViewKind::Media { kind, targets } => {
                let name = match kind {
                    MediaKind::Audio => "audio",
                    MediaKind::Video => "video",
                };
                let target = targets.first().map(String::as_str).unwrap_or("");
                let _ = writeln!(self.out, "{}\n", text(&format!("{name} ({target})")));
            }
            ViewKind::Diagram(diagram) => match diagram {
                DiagramView::Svg(path) => {
                    let path = self.file(path);
                    let _ = writeln!(
                        self.out,
                        "#adoc-image(image({}, alt: \"Diagram\"))\n",
                        string(&path)
                    );
                }
                DiagramView::Pending { source, .. } | DiagramView::Failed { source, .. } => {
                    let _ = writeln!(
                        self.out,
                        "#adoc-code(raw({}, block: true))\n",
                        string(source)
                    );
                }
            },
            ViewKind::Stem { latex, source, .. } => match self.stem(*latex, source, true) {
                Some(call) => {
                    let _ = writeln!(self.out, "{call}\n");
                }
                None => {
                    let _ = writeln!(
                        self.out,
                        "#adoc-code(raw({}, block: true))\n",
                        string(source)
                    );
                }
            },
            ViewKind::Passthrough(content) => {
                let _ = writeln!(self.out, "{}\n", text(content));
            }
            ViewKind::ThematicBreak => self.push("#adoc-break()\n\n"),
            ViewKind::PageBreak => self.push("#pagebreak(weak: true)\n\n"),
            ViewKind::Toc => self.push("#adoc-toc()\n\n"),
            ViewKind::Unsupported { source, .. } => {
                let _ = writeln!(self.out, "#adoc-unsupported({})\n", string(source));
            }
        }
    }

    /// The image's file, when it can be shown: a missing or unreadable image is recorded, to be
    /// shown as its alt text, as asciidoctor-pdf does.
    fn usable_image<'i>(&mut self, image: &'i ViewImage, span: &SourceSpan) -> Option<&'i Path> {
        let Some(path) = &image.path else {
            self.missing
                .push((format!("image not found: {}", image.target), span.clone()));
            return None;
        };
        if !self.options.access.permits(path) {
            self.missing.push((
                format!("image is outside the workspace roots: {}", image.target),
                span.clone(),
            ));
            return None;
        }
        if let Some(problem) = image_problem(path) {
            self.missing.push((
                format!("image could not be read: {} ({problem})", image.target),
                span.clone(),
            ));
            return None;
        }
        Some(path)
    }

    fn block_image(&mut self, block: &ViewBlock, image: &ViewImage) {
        let Some(path) = self.usable_image(image, &block.span) else {
            let _ = writeln!(self.out, "#adoc-missing-image({})\n", string(&image.alt));
            return;
        };
        let path = self.file(path);
        // As asciidoctor-pdf sizes it: `pdfwidth`, else `scaledwidth`, else `width`.
        let width = ["pdfwidth", "scaledwidth"]
            .iter()
            .find_map(|name| block.attributes.get(*name).map(String::as_str))
            .or(image.width.as_deref())
            .and_then(image_size)
            .map(|width| format!(", width: {width}"))
            .unwrap_or_default();
        // A float places it as an alignment does.
        let align = ["float", "align"]
            .iter()
            .find_map(|name| block.attributes.get(*name))
            .map(|align| format!(", align-to: {}", string(align)))
            .unwrap_or_default();
        let shown = format!(
            "image({}, alt: {}{width})",
            string(&path),
            string(&alt_text(image))
        );
        // `link=` makes the image a link, as asciidoctor-pdf does.
        let shown = match block.attributes.get("link") {
            Some(link) => format!("link({}, {shown})", string(link)),
            None => shown,
        };
        let _ = writeln!(self.out, "#adoc-image({shown}{align})\n");
    }

    fn table(&mut self, block: &ViewBlock, table: &ViewTable) {
        let autowidth = block.options.contains("autowidth");
        let columns: Vec<String> = table
            .columns
            .iter()
            .map(|column| match column.width {
                // An automatic width sizes each column to its content.
                _ if autowidth => "auto".to_owned(),
                ColumnWidth::Proportional(width) => format!("{}fr", width.max(1)),
                ColumnWidth::Percentage(width) => format!("{width}%"),
                ColumnWidth::Auto => "auto".to_owned(),
            })
            .collect();
        let columns = if columns.is_empty() {
            let count = table
                .header
                .as_ref()
                .or(table.rows.first())
                .map_or(1, |row| row.iter().map(|cell| cell.colspan.max(1)).sum());
            vec![if autowidth { "auto" } else { "1fr" }.to_owned(); count]
        } else {
            columns
        };
        let header = table.header.as_ref().map_or_else(
            || "none".to_owned(),
            |cells| {
                let cells: Vec<String> = cells.iter().map(|cell| self.cell(cell, true)).collect();
                format!("({},)", cells.join(", "))
            },
        );
        let mut rows = Vec::new();
        for row in &table.rows {
            for cell in row {
                rows.push(self.cell(cell, false));
            }
        }
        let footer = table.footer.as_ref().map_or_else(
            || "none".to_owned(),
            |cells| {
                let cells: Vec<String> = cells.iter().map(|cell| self.cell(cell, false)).collect();
                format!("({},)", cells.join(", "))
            },
        );
        // Every row, the header's and footer's too: the last draws the frame's bottom.
        let row_count = table.rows.len()
            + usize::from(table.header.is_some())
            + usize::from(table.footer.is_some());
        let mut options = format!(", row-count: {row_count}");
        for name in ["frame", "grid", "stripes"] {
            if let Some(value) = block.attributes.get(name) {
                let _ = write!(options, ", {name}: {}", string(value));
            }
        }
        // `width` as a percentage of the page; with `%autowidth` and no width, the content's.
        let width = block
            .attributes
            .get("width")
            .and_then(|width| width.trim().trim_end_matches('%').parse::<f64>().ok())
            .filter(|width| *width > 0.0);
        match width {
            Some(width) => {
                let width = typst::number(width.min(100.0));
                let _ = write!(options, ", width: {}%", width.trim_end_matches(".0"));
            }
            None if autowidth => options.push_str(", width: auto"),
            None => {}
        }
        let _ = writeln!(
            self.out,
            "#adoc-table(({},), {header}, ({}), {footer}{options})\n",
            columns.join(", "),
            rows.iter()
                .map(|row| format!("{row}, "))
                .collect::<String>()
        );
    }

    fn cell(&mut self, cell: &ViewCell, header: bool) -> String {
        let body = if cell.style == CellStyle::AsciiDoc {
            let start = self.out.len();
            self.blocks(&cell.blocks, Gaps::Inside);
            self.out.split_off(start)
        } else {
            let mut parts = Vec::new();
            for block in &cell.blocks {
                match &block.kind {
                    ViewKind::Paragraph(content) => {
                        let inline = self.inlines(content);
                        parts.push(match cell.style {
                            CellStyle::Emphasis => format!("#emph[{inline}]"),
                            CellStyle::Strong => format!("#strong[{inline}]"),
                            CellStyle::Header if !header => format!("#strong[{inline}]"),
                            CellStyle::Monospace => format!("#adoc-codespan[{inline}]"),
                            CellStyle::Literal => {
                                format!(
                                    "#raw({}, block: true)",
                                    string(&ViewInline::plain_text(content))
                                )
                            }
                            _ => inline,
                        });
                    }
                    _ => {
                        let start = self.out.len();
                        self.block(block);
                        parts.push(self.out.split_off(start));
                    }
                }
            }
            let mut body = parts.join("\n\n#v(prose-bottom)\n\n");
            body.push_str("\n\n");
            body
        };
        let align = match cell.align {
            Align::Start => "left",
            Align::Centre => "center",
            Align::End => "right",
        };
        let valign = match cell.valign {
            VAlign::Top => "top",
            VAlign::Middle => "horizon",
            VAlign::Bottom => "bottom",
        };
        let align = format!("{align} + {valign}");
        format!(
            "table.cell(colspan: {}, rowspan: {}, align: {align})[{body}]",
            cell.colspan.max(1),
            cell.rowspan.max(1)
        )
    }

    /// The virtual path a file is served at; the same file always gets the same path.
    pub(crate) fn file(&mut self, path: &Path) -> String {
        if let Some(existing) = self.file_paths.get(path) {
            return existing.clone();
        }
        let extension = path
            .extension()
            .and_then(|extension| extension.to_str())
            .unwrap_or("bin")
            .to_ascii_lowercase();
        let virtual_path = format!("/files/{}.{extension}", stable_hash(path));
        self.file_paths
            .insert(path.to_path_buf(), virtual_path.clone());
        self.files.push((virtual_path.clone(), path.to_path_buf()));
        virtual_path
    }

    pub(crate) fn inlines(&mut self, inlines: &[ViewInline]) -> String {
        let mut out = String::new();
        for inline in inlines {
            self.inline(&mut out, inline);
        }
        out
    }

    fn inline(&mut self, out: &mut String, inline: &ViewInline) {
        match inline {
            ViewInline::Text(value) | ViewInline::Raw(value) => {
                out.push_str(&text(&flowing(value)));
            }
            ViewInline::Strong(content) => {
                let inner = self.inlines(content);
                let _ = write!(out, "#strong[{inner}]");
            }
            ViewInline::Emphasis(content) => {
                let inner = self.inlines(content);
                let _ = write!(out, "#emph[{inner}]");
            }
            ViewInline::Code(content) => {
                let inner = self.inlines(content);
                let _ = write!(out, "#adoc-codespan[{inner}]");
            }
            ViewInline::Mark(content) => {
                let inner = self.inlines(content);
                let _ = write!(out, "#adoc-mark[{inner}]");
            }
            ViewInline::Superscript(content) => {
                let inner = self.inlines(content);
                let _ = write!(out, "#adoc-super[{inner}]");
            }
            ViewInline::Subscript(content) => {
                let inner = self.inlines(content);
                let _ = write!(out, "#adoc-sub[{inner}]");
            }
            ViewInline::Span { roles, content } => {
                let mut inner = self.inlines(content);
                for role in roles {
                    inner = format!("#adoc-role({}, [{inner}])", string(role));
                }
                out.push_str(&inner);
            }
            ViewInline::Link { url, content } => {
                let inner = if content.is_empty() {
                    text(url)
                } else {
                    self.inlines(content)
                };
                let _ = write!(out, "#adoc-link({}, [{inner}])", string(url));
            }
            ViewInline::Xref {
                target,
                link,
                content,
                ..
            } => {
                let inner = if content.is_empty() {
                    text(link.title.as_deref().unwrap_or(target))
                } else {
                    self.inlines(content)
                };
                match self.xref_destination(target, link) {
                    Some(destination) => {
                        let _ = write!(out, "#adoc-link({destination}, [{inner}])");
                    }
                    None => out.push_str(&inner),
                }
            }
            ViewInline::Anchor(id) => {
                let _ = write!(out, "#metadata(none)#{}", self.label(id));
            }
            ViewInline::Image(image) => match self.usable_image(image, &self.span.clone()) {
                Some(path) => {
                    let path = self.file(path);
                    let size = image
                        .width
                        .as_deref()
                        .and_then(image_size)
                        .map(|width| format!(", width: {width}"))
                        .or_else(|| {
                            image
                                .height
                                .as_deref()
                                .and_then(image_size)
                                .map(|height| format!(", height: {height}"))
                        })
                        .unwrap_or_default();
                    let _ = write!(
                        out,
                        "#box(image({}, alt: {}{size}))",
                        string(&path),
                        string(&alt_text(image))
                    );
                }
                None => out.push_str(&text(&format!("[{}]", image.alt))),
            },
            ViewInline::Icon(name) => out.push_str(&text(&format!("[{name}]"))),
            ViewInline::FootnoteRef(number) => {
                let label = self.label(&footnote_id(*number));
                let _ = write!(out, "#adoc-footnote-ref({number}, {label})");
            }
            ViewInline::LineBreak => out.push_str("#linebreak()"),
            ViewInline::Keyboard(keys) => {
                let keys: Vec<String> = keys.iter().map(|key| string(key)).collect();
                let _ = write!(out, "#adoc-kbd(({},))", keys.join(", "));
            }
            ViewInline::Button(label) => {
                let _ = write!(out, "#adoc-button({})", string(label));
            }
            ViewInline::Menu(items) => {
                // Submenus are separated by `>` or `,`, as Asciidoctor reads them.
                let items: Vec<String> = items
                    .iter()
                    .flat_map(|item| {
                        let separator = if item.contains('>') { '>' } else { ',' };
                        item.split(separator).map(str::trim).collect::<Vec<_>>()
                    })
                    .filter(|item| !item.is_empty())
                    .map(string)
                    .collect();
                let _ = write!(out, "#adoc-menu(({},))", items.join(", "));
            }
            ViewInline::Stem { latex, source, .. } => match self.stem(*latex, source, false) {
                Some(call) => out.push_str(&call),
                None => {
                    let _ = write!(out, "#adoc-codespan[{}]", text(source));
                }
            },
            ViewInline::IndexTerm { terms, content } => {
                let inner = self.inlines(content);
                let terms: Vec<String> = terms.iter().map(|term| string(term)).collect();
                // The marker the index finds the term and its page by.
                let _ = write!(
                    out,
                    "{inner}#metadata(({},))<adoc-index-term>",
                    terms.join(", ")
                );
            }
        }
    }

    /// Where a cross reference leads in this document: a label it defines, a page of the
    /// book, or the site. `None` leaves the reference as text.
    fn xref_destination(&self, target: &str, link: &adoc_render::ResolvedLink) -> Option<String> {
        let fragment = link.fragment.clone().or_else(|| {
            target
                .split_once('#')
                .map(|(_, fragment)| fragment.to_owned())
        });
        // A reference that leads nowhere stays text; it must not fall back to this page.
        if link.unresolved {
            return None;
        }
        let page = match &link.target {
            Some(location) if location.path != self.source => self.pages.get(&location.path),
            _ => Some(&self.key),
        };
        if let Some(page) = page {
            let candidates = [
                fragment
                    .as_deref()
                    .map(|fragment| label_name(page, fragment)),
                Some(label_name(page, "")),
            ];
            for candidate in candidates.into_iter().flatten() {
                if self.labels.contains(&candidate) {
                    return Some(format!("label({})", string(&candidate)));
                }
            }
            return None;
        }
        if let Some(url) = link
            .target
            .as_ref()
            .and_then(|location| self.options.page_urls.get(&location.path))
        {
            let mut url = url.clone();
            if let Some(fragment) = &fragment {
                url.push('#');
                url.push_str(fragment);
            }
            return Some(string(&url));
        }
        let site = self.options.site_url.as_deref()?;
        let file = target.split('#').next().unwrap_or(target);
        let file = file
            .rsplit(['$', ':'])
            .next()
            .unwrap_or(file)
            .replace(".adoc", ".html");
        let mut url = format!("{}/{file}", site.trim_end_matches('/'));
        if let Some(fragment) = fragment {
            url.push('#');
            url.push_str(&fragment);
        }
        Some(string(&url))
    }
}

fn collect_labels(key: &str, blocks: &[ViewBlock], labels: &mut HashSet<String>) {
    fn inline_anchors(key: &str, inlines: &[ViewInline], labels: &mut HashSet<String>) {
        for inline in inlines {
            match inline {
                ViewInline::Anchor(id) => {
                    labels.insert(label_name(key, id));
                }
                ViewInline::Strong(content)
                | ViewInline::Emphasis(content)
                | ViewInline::Code(content)
                | ViewInline::Mark(content)
                | ViewInline::Superscript(content)
                | ViewInline::Subscript(content)
                | ViewInline::Span { content, .. }
                | ViewInline::Link { content, .. }
                | ViewInline::Xref { content, .. } => inline_anchors(key, content, labels),
                _ => {}
            }
        }
    }
    for block in blocks {
        if let Some(id) = &block.id {
            labels.insert(label_name(key, id));
        }
        inline_anchors(key, &block.title, labels);
        match &block.kind {
            ViewKind::Section { blocks, title, .. } => {
                inline_anchors(key, title, labels);
                collect_labels(key, blocks, labels);
            }
            ViewKind::Paragraph(content) => inline_anchors(key, content, labels),
            ViewKind::List { items, .. } => {
                for item in items {
                    inline_anchors(key, &item.content, labels);
                    collect_labels(key, &item.blocks, labels);
                }
            }
            ViewKind::DescriptionList(items) => {
                for item in items {
                    inline_anchors(key, &item.term, labels);
                    inline_anchors(key, &item.content, labels);
                    collect_labels(key, &item.blocks, labels);
                }
            }
            ViewKind::CalloutList(items) => {
                for item in items {
                    inline_anchors(key, &item.content, labels);
                    collect_labels(key, &item.blocks, labels);
                }
            }
            ViewKind::Admonition { blocks, .. }
            | ViewKind::Quote { blocks, .. }
            | ViewKind::Sidebar(blocks)
            | ViewKind::Example(blocks)
            | ViewKind::Open(blocks) => collect_labels(key, blocks, labels),
            ViewKind::Table(table) => {
                for cell in table
                    .header
                    .iter()
                    .flatten()
                    .chain(table.rows.iter().flatten())
                    .chain(table.footer.iter().flatten())
                {
                    collect_labels(key, &cell.blocks, labels);
                }
            }
            _ => {}
        }
    }
}

/// An image's alt text, or, as Asciidoctor defaults it, its file name without the extension
/// and with `-` and `_` as spaces, so every image carries a text alternative.
/// Why the image at `path` cannot be shown, if it cannot: decoded as Typst decodes it when it
/// lays the page out (memoised, so the work is not repeated), where a failure would fail the
/// whole document.
fn image_problem(path: &Path) -> Option<String> {
    // `::typst`, the crate, not this crate's `typst` module.
    use ::typst::{
        foundations::Bytes,
        visualize::{ImageFormat, RasterImage, SvgImage, VectorFormat},
    };
    let data = match std::fs::read(path) {
        Ok(data) => data,
        Err(error) => return Some(error.to_string()),
    };
    let format = ImageFormat::detect(&data);
    let data = Bytes::new(data);
    match format {
        Some(ImageFormat::Raster(format)) => RasterImage::plain(data, format)
            .err()
            .map(|error| error.to_string()),
        Some(ImageFormat::Vector(VectorFormat::Svg)) => {
            SvgImage::new(data).err().map(|error| format!("{error:?}"))
        }
        Some(ImageFormat::Vector(VectorFormat::Pdf)) => None,
        None => Some("an unrecognised image format".to_owned()),
    }
}

fn alt_text(image: &ViewImage) -> String {
    if !image.alt.trim().is_empty() {
        return image.alt.clone();
    }
    let name = image
        .target
        .rsplit(['/', '$', ':'])
        .next()
        .unwrap_or(&image.target);
    let stem = name.rsplit_once('.').map_or(name, |(stem, _)| stem);
    stem.replace(['-', '_'], " ")
}

/// Flowing text as Prawn sets it: line breaks become spaces and runs of spaces collapse.
fn flowing(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    let mut space = false;
    for character in value.chars() {
        if character == ' ' || character == '\n' || character == '\t' {
            if !space {
                out.push(' ');
            }
            space = true;
        } else {
            out.push(character);
            space = false;
        }
    }
    out
}

